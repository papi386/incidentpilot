import type { IncidentStatus } from "./types";

const ALLOWED_TRANSITIONS: Readonly<Record<IncidentStatus, readonly IncidentStatus[]>> = {
  RECEIVED: ["VALIDATING", "REJECTED", "SECURITY_ABORTED", "FAILED_SAFE", "CANCELLED"],
  VALIDATING: ["AUTHORIZED", "POLICY_DENIED", "SECURITY_ABORTED", "FAILED_SAFE", "CANCELLED"],
  AUTHORIZED: ["TRIAGING", "POLICY_DENIED", "FAILED_SAFE", "CANCELLED"],
  TRIAGING: ["CONTEXT_BUILDING", "NEEDS_HUMAN", "BUDGET_EXHAUSTED", "SECURITY_ABORTED", "FAILED_SAFE", "CANCELLED"],
  CONTEXT_BUILDING: ["INVESTIGATING", "NEEDS_HUMAN", "BUDGET_EXHAUSTED", "SECURITY_ABORTED", "FAILED_SAFE", "CANCELLED"],
  INVESTIGATING: ["DIAGNOSIS_READY", "NEEDS_HUMAN", "BUDGET_EXHAUSTED", "FAILED_SAFE", "CANCELLED"],
  DIAGNOSIS_READY: ["AUTONOMY_GATE", "NEEDS_HUMAN", "FAILED_SAFE", "CANCELLED"],
  AUTONOMY_GATE: ["NEEDS_HUMAN", "PATCH_PLANNING", "REPORT_ONLY", "POLICY_DENIED", "CANCELLED"],
  NEEDS_HUMAN: ["PATCH_PLANNING", "REPORT_ONLY", "CANCELLED"],
  PATCH_PLANNING: ["PATCH_GENERATING", "NEEDS_HUMAN", "BUDGET_EXHAUSTED", "FAILED_SAFE", "CANCELLED"],
  PATCH_GENERATING: ["PATCH_STATIC_VALIDATION", "REPLAN", "NEEDS_HUMAN", "BUDGET_EXHAUSTED", "FAILED_SAFE", "CANCELLED"],
  PATCH_STATIC_VALIDATION: ["VERIFYING", "REPLAN", "SECURITY_ABORTED", "FAILED_SAFE", "CANCELLED"],
  VERIFYING: ["VERIFIED", "REPLAN", "NEEDS_HUMAN", "FAILED_SAFE", "CANCELLED"],
  REPLAN: ["PATCH_PLANNING", "NEEDS_HUMAN", "BUDGET_EXHAUSTED", "FAILED_SAFE", "CANCELLED"],
  VERIFIED: ["ACTION_POLICY_GATE", "REPORT_ONLY", "FAILED_SAFE", "CANCELLED"],
  ACTION_POLICY_GATE: ["CREATE_DRAFT_PR", "REPORT_ONLY", "POLICY_DENIED", "CANCELLED"],
  REPORT_ONLY: ["COMPLETED"],
  CREATE_DRAFT_PR: ["COMPLETED", "FAILED_SAFE", "CANCELLED"],
  COMPLETED: [],
  REJECTED: [],
  POLICY_DENIED: [],
  BUDGET_EXHAUSTED: [],
  SECURITY_ABORTED: [],
  FAILED_SAFE: [],
  CANCELLED: []
};

export function canTransition(from: IncidentStatus, to: IncidentStatus): boolean {
  return ALLOWED_TRANSITIONS[from].includes(to);
}

export function assertTransition(from: IncidentStatus, to: IncidentStatus): void {
  if (!canTransition(from, to)) {
    throw new Error(`Illegal incident status transition: ${from} -> ${to}`);
  }
}
